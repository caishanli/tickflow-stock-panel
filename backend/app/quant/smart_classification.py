# 红利策略关键词
_DIVIDEND_KEYWORDS = [
    "红利", "股息", "高分红", "高股息", "现金牛", "分红",
    "红利低波", "红利质量", "红利100", "红利指数",
]


def _match_keywords(name: str, keywords: list[str]) -> bool:
    """检查名称是否包含关键词列表中的任一关键词。"""
    return any(kw in name for kw in keywords)


def classify_etf(code: str, name: str = "") -> str:
    """对单只 ETF 进行智能分类。

    基于 ETF 名称关键词进行分类。

    Args:
        code: ETF 代码（如 518880.XSHG 或 518880）
        name: ETF 名称

    Returns:
        分类标签（如 大宗商品、海外指数、港股、A股指数、科技 等）
    """
    if not name:
        return "其他"

    # 1. 大宗商品（优先级最高，避免被其他分类误判）
    if _match_keywords(name, _COMMODITY_KEYWORDS):
        return "大宗商品"

    # 2. 红利策略（在行业之前判断，避免被金融/消费误判）
    if _match_keywords(name, _DIVIDEND_KEYWORDS):
        return "红利"

    # 3. 港股（在海外指数之前判断，因为港股也是境外市场）
    if _match_keywords(name, _HK_KEYWORDS):
        return "港股"

    # 4. 海外指数
    if _match_keywords(name, _OVERSEAS_KEYWORDS):
        return "海外指数"

    # 5. A股指数（宽基+债券）
    if _match_keywords(name, _INDEX_KEYWORDS):
        return "A股指数"

    # 6. 行业分类
    for sector, keywords in _SECTOR_KEYWORDS.items():
        if _match_keywords(name, keywords):
            return sector

    # 7. 通过代码前缀启发式判断（兜底）
    pure = code.split(".")[0] if "." in code else code
    if pure.startswith("511"):
        return "债券"
    if pure.startswith("513"):
        return "海外指数"  # 513xxx 多为跨境ETF
    if pure.startswith("588"):
        return "A股指数"  # 588xxx 为科创板ETF

    return "其他"


def get_smart_name(code: str, base_name: str) -> str:
    """获取智能分类后的标的名称。

    Args:
        code: ETF 代码（如 518880.XSHG）
        base_name: 基础名称（来自通达信或聚宽）

    Returns:
        带分类标签的名称（如 [大宗商品] 黄金ETF）
    """
    if not base_name or base_name == code:
        return base_name

    category = classify_etf(code, base_name)
    if category == "其他":
        return base_name
    return f"[{category}] {base_name}"


def get_all_classifications() -> dict[str, str]:
    """返回所有已知 ETF 的分类映射 {代码: 分类}。

    用于批量查询或调试。
    """
    from app.quant.jqengine.engine.jq.jq_names import load_jq_names

    jq_names = load_jq_names() or {}
    result = {}

    for jq_code, name in jq_names.items():
        pure = jq_code.split(".")[0] if "." in jq_code else jq_code
        category = classify_etf(pure, name)
        if category != "其他":
            result[pure] = category

    return result


def get_category_etfs(category: str) -> list[str]:
    """返回指定分类下的所有 ETF 代码。

    Args:
        category: 分类标签（如 大宗商品、科技）

    Returns:
        该分类下的 ETF 代码列表
    """
    classifications = get_all_classifications()
    return [code for code, cat in classifications.items() if cat == category]
